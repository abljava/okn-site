export function getObjectPdfs(number, source) {
  const parsed = Number.parseInt(String(number ?? "").trim(), 10);
  if (!Number.isFinite(parsed)) return [];
  const map = pdfMaps[source];
  if (!map) return [];
  return map[String(parsed)] ?? [];
}
